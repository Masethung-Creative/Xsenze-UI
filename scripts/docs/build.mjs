// Builds the data the docs site reads, from scripts/docs/site.config.mjs and the pages themselves:
//   docs/site.generated.js     version, public addresses and the page list (every page loads it)
//   docs/search.generated.js   everything the Ctrl+K search can find (loaded when search opens)
// Run by `npm run build`, or on its own with `npm run docs`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const r = (...p) => path.join(root, ...p);
const read = (p) => fs.readFileSync(r(p), 'utf8');

const strip = (s) =>
  s
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&rarr;/g, '→')
    .replace(/\s+/g, ' ')
    .trim();

/** Public addresses, all from package.json, so no page types the owner, repository or version by hand. */
export function siteUrls(pkg) {
  const repo = String(pkg.repository?.url || pkg.repository || '')
    .replace(/^git\+/, '')
    .replace(/\.git$/, '');
  const slug = repo.replace(/^https:\/\/github\.com\//, '');
  const site = pkg.homepage || '';
  return {
    site,
    docs: site ? new URL('docs/', site).href : '',
    repo,
    cdn: slug ? `https://cdn.jsdelivr.net/gh/${slug}@v${pkg.version}/dist` : '',
    npm: slug ? `github:${slug}#v${pkg.version}` : '',
  };
}

export async function buildDocs() {
  const pkg = JSON.parse(read('package.json'));
  const config = (await import(pathToFileURL(r('scripts/docs/site.config.mjs')).href + `?t=${Date.now()}`)).default;
  const urls = siteUrls(pkg);
  const items = [];
  const add = (item) => items.push(Object.fromEntries(Object.entries(item).filter(([, v]) => v !== '' && v != null && v !== false)));

  for (const page of config.pages) {
    const html = read(`docs/${page.file}`);
    const lead = strip((/<p class="xz-lead">([\s\S]*?)<\/p>/.exec(html) || [, ''])[1]);
    add({ label: page.label, group: 'Pages', href: page.file, meta: lead.length > 70 ? lead.slice(0, 68).replace(/\s\S*$/, '') + '…' : lead, icon: 'file-text', pin: true });
    // Sections (h2) and their sub-headings (h3 with an id).
    const sections = [];
    for (const m of html.matchAll(/<section class="doc-section" id="([^"]+)"[^>]*>[\s\S]*?<h2[^>]*>([\s\S]*?)<\/h2>/g)) sections.push({ id: m[1], title: strip(m[2]), at: m.index });
    const group = page.kind === 'components' ? 'Components' : 'Sections';
    for (const s of sections) add({ label: s.title, group, href: `${page.file}#${s.id}`, meta: page.label, icon: page.kind === 'components' ? 'component' : 'list' });
    for (const m of html.matchAll(/<h3 id="([^"]+)"[^>]*>([\s\S]*?)<\/h3>/g)) {
      const parent = sections.filter((s) => s.at < m.index).pop();
      if (!parent) continue;
      add({ label: strip(m[2]), group: 'Sections', href: `${page.file}#${m[1]}`, meta: `${page.label} › ${parent.title}`, keywords: parent.title });
    }
  }

  // Tokens, with their values.
  const flat = JSON.parse(read('dist/tokens/tokens.json'));
  const where = (name) => (config.tokens.find(([re]) => re.test(name)) || [, 'foundations.html'])[1];
  for (const [name, value] of Object.entries(flat.core)) add({ label: `--xz-${name}`, group: 'Tokens', href: where(name), meta: String(value) });
  for (const [name, value] of Object.entries(flat.light)) add({ label: `--xz-${name}`, group: 'Tokens', href: where(name), meta: value === flat.dark[name] ? String(value) : `${value} · dark ${flat.dark[name]}`, keywords: 'theme light dark' });

  // Icons, with the words they are known by.
  const icons = (await import(pathToFileURL(r('scripts/icons.list.mjs')).href)).default;
  const tagsFile = r('node_modules/lucide-static/tags.json');
  const tags = fs.existsSync(tagsFile) ? JSON.parse(fs.readFileSync(tagsFile, 'utf8')) : {};
  for (const name of icons) add({ label: name, group: 'Icons', href: 'foundations.html#icons', icon: name, meta: 'Icon', keywords: (tags[name] || []).join(' ') });

  const banner = '// Generated by scripts/docs/build.mjs from scripts/docs/site.config.mjs and the pages. Do not edit.\n';
  const site = { version: pkg.version, urls, pages: config.pages.map(({ file, label }) => ({ file, label })) };
  fs.writeFileSync(r('docs/site.generated.js'), `${banner}window.XZ_SITE = ${JSON.stringify(site)};\n`);
  fs.writeFileSync(r('docs/search.generated.js'), `${banner}window.XZ_SEARCH = ${JSON.stringify(items)};\n`);
  return { pages: config.pages.length, items: items.length };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { pages, items } = await buildDocs();
  console.log(`Docs data: ${pages} pages, ${items} search entries`);
}
